// Generate semantic stroke weights from the Unicode Character Database.
// No font outlines or third-party renderer geometry are used.
// Prints Rust source; it never changes the working tree itself.
const url = "https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt";
const response = await fetch(url);
if (!response.ok) throw new Error(`Unicode download failed: ${response.status}`);
const weights = Array(128).fill(0);
let count = 0;
for (const line of (await response.text()).split("\n")) {
  const [hex, name] = line.split(";");
  const code = Number.parseInt(hex, 16);
  if (!(code >= 0x2500 && code <= 0x257f)) continue;
  if (/DASH|DOUBLE|SINGLE|ARC|DIAGONAL/.test(name)) continue;
  const description = name.replace("BOX DRAWINGS ", "");
  const defaultWeight = description.startsWith("LIGHT ") ? 1 : description.startsWith("HEAVY ") ? 2 : 0;
  let packed = 0;
  for (const clause of description.split(" AND ")) {
    const weight = clause.includes("HEAVY") ? 2 : clause.includes("LIGHT") ? 1 : defaultWeight;
    if (!weight) throw new Error(`Unrecognized weight: ${name}`);
    const directions = clause.split(" ").flatMap(word => word === "HORIZONTAL" ? ["LEFT", "RIGHT"] : word === "VERTICAL" ? ["UP", "DOWN"] : [word]);
    for (const [index, direction] of ["LEFT", "RIGHT", "UP", "DOWN"].entries()) {
      if (directions.includes(direction)) packed |= weight << (2 * index);
    }
  }
  if (!packed) throw new Error(`Unrecognized directions: ${name}`);
  weights[code - 0x2500] = packed;
  count++;
}
if (count !== 80) throw new Error(`Expected 80 solid light/heavy glyphs, got ${count}`);
console.log(`// Generated by scripts/generate-terminal-glyph-data.mjs from Unicode 17.0.0.
// Semantic character data only. See THIRD_PARTY_NOTICES.md and licenses/UNICODE.txt.
// Two bits per direction: left, right, up, down; 0 absent, 1 light, 2 heavy.
pub(super) const SOLID_STROKES: [u8; 128] = [`);
for (let row = 0; row < 128; row += 8) {
  console.log(`    ${weights.slice(row, row + 8).map(value => `0x${value.toString(16).padStart(2, "0")}`).join(", ")}, // U+${(0x2500 + row).toString(16).toUpperCase()}`);
}
console.log("]; ");
